// チャート表示レイアウト
import theme from '@/theme/theme';
import { CssBaseline, ThemeProvider } from '@mui/material';
import { AppRouterCacheProvider } from '@mui/material-nextjs/v15-appRouter';
import type { Metadata } from 'next';
import { redirect } from 'next/navigation';
import { ApiClient } from '@/lib/api/apiClient';

const apiClient = new ApiClient


export const metadata: Metadata = {
    title: 'Create Next App',
    description: 'Generated by create next app',
};

import { cookies } from 'next/headers';

async function getDjangoUserInfo() {
    // 1. ブラウザからNext.jsサーバーへのリクエストに含まれるCookieを取得
    const cookieStore = await cookies();
    const sessionId = cookieStore.get('sessionid')?.value;
    const csrfToken = cookieStore.get('csrftoken')?.value; // CSRFトークンも必要なら同様に

    // 2. セッションIDがなければ、未ログイン状態として処理
    if (!sessionId) {
        console.log('No session ID found. User is not logged in.');
        return null; 
    }

    // 3. Next.jsサーバーからDjangoサーバーへのfetchリクエストを作成
    try {   
        const response = await fetch('http://localhost:8000/api/users/auth/user-info/', {
            method: 'GET',
            headers: {
                // 4. 取得したCookieを手動で`Cookie`ヘッダーに設定して転送する
                'Cookie': `sessionid=${sessionId}${csrfToken ? `; csrftoken=${csrfToken}` : ''}`,
            },
            // サーバー間通信なので'credentials'は不要
        });
            
        if (!response.ok) {
            // エラーハンドリング
            console.error('Failed to fetch user info from Django:', response.statusText);
            return null;
        }

        return await response.json();

    } catch (error) {
        console.error('Error during fetch to Django:', error);
        return null;
    }
}


export default async function MainLayout({
    children,
}: Readonly<{
    children: React.ReactNode;
}>) {
    const session = await getDjangoUserInfo()

    console.log('session',session)

    const isSession = async() => {
        const response = await apiClient.request('/api/users/auth/user-info/', 'GET', session);
        console.log(response)
        if(response.ok){
            console.log(response)
            redirect('/main/graph')
        }else if(response.status == 403) {
            console.log('forbidden')
            redirect('/register')
        }else {
            console.log("予期せぬエラー",response)
        }
    }

    await isSession()

    return (
        <AppRouterCacheProvider>
            <CssBaseline />
            <ThemeProvider theme={theme}>
                {children}
            </ThemeProvider>
        </AppRouterCacheProvider>
    );
}
